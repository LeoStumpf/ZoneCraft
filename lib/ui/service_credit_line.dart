import 'package:flutter/material.dart';

/// One line naming a free service the app relies on (or why giving back to it
/// matters), drawn the same everywhere: a small hand-with-heart and quiet text.
/// The words live in `data/service_credits.dart`.
class ServiceCreditLine extends StatelessWidget {
  const ServiceCreditLine(this.text, {super.key});

  final String text;

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final color = theme.colorScheme.onSurfaceVariant;
    return Row(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Padding(
          padding: const EdgeInsets.only(top: 1),
          child: Icon(
            Icons.volunteer_activism_outlined,
            size: 16,
            color: color,
          ),
        ),
        const SizedBox(width: 8),
        Expanded(
          child: Text(
            text,
            style: theme.textTheme.bodySmall?.copyWith(color: color),
          ),
        ),
      ],
    );
  }
}
